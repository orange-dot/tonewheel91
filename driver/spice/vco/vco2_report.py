#!/usr/bin/env python3
"""VCO-2 report -> <out>/summary.md."""
import json, pathlib
import numpy as np
import vco2
here = vco2.OUT
J = lambda n: json.loads((here / n).read_text())
L = []
def P(s=''): L.append(s)
NAMES = ['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B']
name = lambda n: f'{NAMES[n % 12]}{n // 12 - 1}'

P('# Step 2 - VCO-2 study: exponential converter and reset-type saw core'); P()
P('Generated by `driver/spice/vco/vco2_report.py`. Circuit: `driver/spice/vco/vco2.cir` (16 transistors, the lab\'s BC547C/BC557C engineering models, ideal rails).'); P()
calA, calB = J('cal-A.json'), J('cal-B.json')
P('## Boards and trim'); P()
P('Both boards are trimmed the same way: scale until C2 -> C6 is four octaves, pitch until A4 is 440 Hz, to within 0.05 cents.'); P()
P('| board | differs from nominal | RSCALE | VTUNE | trim passes |'); P('|---|---|---:|---:|---:|')
P(f"| A | nominal | {calA['params']['rscale']:.2f} ohm | {calA['params']['vtune']:.4f} V | {len(calA['log'])} |")
P(f"| B | hfe 450, Early 80 V, CT +1 %, RLIM 110 ohm, converter pair 4 % apart | {calB['params']['rscale']:.2f} ohm | {calB['params']['vtune']:.4f} V | {len(calB['log'])} |"); P()

tA, tB = J('track-A.json'), J('track-B.json')
S = J('shape-A.json')
P('## Tracking after trim (cents from equal temperament)'); P()
P('| note | target (Hz) | A | B | B - A | beat A-B (Hz) | swing A (V) | pitch law, residual A |'); P('|---|---:|---:|---:|---:|---:|---:|---:|')
for a, b, r in zip(tA, tB, S['law_A']['residual_cents']):
    P(f"| {name(a['note'])} | {a['target_hz']:.2f} | {a['cents']:+.2f} | {b['cents']:+.2f} | {b['cents'] - a['cents']:+.2f} | "
      f"{abs(b['f_hz'] - a['f_hz']):.3f} | {a['top'] - a['bottom']:.4f} | {r:+.2f} |")
P()
for b in ('A', 'B'):
    w = S[f'law_{b}']
    P(f"Pitch law for {b}: `1/f = 1/(2^(a + s*cv) + b) + td` with s = {w['scale']:.5f}, extra current b = {w['extra_hz']:+.4f} Hz, "
      f"dead time td = {w['dead_time_us']:.3f} us; worst residual {max(abs(x) for x in w['residual_cents']):.2f} cents.")
P()

P('## Saw shape (board A)'); P()
P('| note | f (Hz) | H2 | H3 | H4 | H8 | H16 | SPICE - ideal | SPICE - MA | MA - ideal | straight ramp, residual | bow |')
P('|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|')
for r in S['shapes']:
    h, m = r['spice_dbc'], r['ma_dbc']
    cell = lambda k: (f'{h[k-1]:.2f} ({m[k-1]:.2f})' if k <= len(h) else '-')
    P(f"| {name(r['note'])} | {r['f_hz']:.2f} | " + ' | '.join(cell(k) for k in (2, 3, 4, 8, 16)) +
      f" | {r['null_vs_ideal_db']:.1f} | {r['null_vs_ma_db']:.1f} | {r['ma_vs_ideal_db']:.1f} | {r['straight_residual_db']:.1f} | {r['bow_mv']:+.1f} mV |")
P()
P('Harmonics in dB relative to the fundamental, SPICE (MA). The ideal saw has H2 -6.02, H3 -9.54, H4 -12.04, H8 -18.06, H16 -24.08.'); P()
e = S['reset']
P(f"Reset edge at A4, 20 ns grid: the comparator's pulse is {e['square_pulse_us']:.2f} us; from the bottom ({e['bottom']:.3f} V) the capacitor "
  f"reaches 10 % in {e['t10_us']:.2f} us, 90 % in {e['t90_us']:.2f} us and 99 % in {e['t99_us']:.2f} us of the way to the top ({e['top']:.3f} V)."); P()

T = J('temp-A.json')
P('## Temperature (board A, trimmed at 25 C; cents from equal temperament)'); P()
P('| scale resistor | temperature | C2 | A4 | C6 | C2 -> C6 (cents from four octaves) |'); P('|---|---:|---:|---:|---:|---:|')
for tcs in (0.0, 3.3e-3):
    for t in (10.0, 25.0, 40.0):
        c = {r['note']: r['cents'] for r in T if r['tcs'] == tcs and r['temp'] == t}
        P(f"| {'plain' if tcs == 0 else '+3300 ppm/K'} | {t:g} C | {c[36]:+.1f} | {c[69]:+.1f} | {c[84]:+.1f} | {c[84] - c[36]:+.1f} |")
P()
pm = here / 'phrase-measured.json'
if pm.exists():
    M = json.loads(pm.read_text())
    P('## Phrase (stepped CV, real transient, both boards)'); P()
    P('| note | seconds | A (cents) | B (cents) | beat A-B (Hz) |'); P('|---|---:|---:|---:|---:|')
    for r in M['notes']:
        P(f"| {name(r['note'])} | {r['seconds']:g} | {r['a_cents']:+.2f} | {r['b_cents']:+.2f} | {r['beat_hz']:.3f} |")
    P(); P(f"The MA pair in `phrase-pair` is two MA saws {M['ma_pair_detune_cents']:.2f} cents apart on every note."); P()
    if 'warm_notes' in M:
        P('Board B 2 K above its trim temperature, with the +3300 ppm/K scale resistor:'); P()
        P('| note | B (cents) | B - A (cents) | beat A-B (Hz) |'); P('|---|---:|---:|---:|')
        for x in M['warm_notes']:
            P(f"| {name(x['note'])} | {x['b_cents']:+.2f} | {x['diff_cents']:+.2f} | {x['beat_hz']:.3f} |")
        P(); P(f"The MA pair in `phrase-pair-warm` is two MA saws {M['ma_pair_warm_detune_cents']:.2f} cents apart on every note."); P()
P("""## Listening renders (`listen/`, 48 kHz, 24 bit, mono)

Each `-AB.wav` is SPICE, 0.4 s of silence, then MA, at the same RMS.

- `tone-saw-n36-*`, `tone-saw-n60-*`, `tone-saw-n84-*`: board A against the MA saw at the same frequency
- `phrase-saw`: board A alone; MA plays the frequencies A played
- `phrase-pair`: boards A + B, both freshly trimmed; MA is two saws a fixed number of cents apart
- `phrase-pair-warm`: the same with board B 2 K warmer than when it was trimmed

## Method and limits

- `vco2.cir` is a study circuit written for this step, not a board design: no KiCad source, ideal 12 V and
  8 V rails, ideal CV and trim sources, no output coupling. Sixteen transistors, the lab's declared
  engineering models (`models/`), which have no noise, no high-current roll-off and 0.1 ohm bulk resistances.
- ngspice-47, Gear, reltol 1e-5, maximum step min(0.5 us, period/4000), linearized to 1.92 MHz. Periods are
  timed on the falling ramp. On the first draft of the circuit (before RB3 and RB5), a 20 ns maximum step
  instead of 500 ns moved the A4 case by 0.06 cents and the C8 case by 0.15 cents; not repeated on the final circuit.
- The SPICE saw falls and resets upward; it is inverted for the comparisons and the renders (MA's saw rises).
- Tones are the steady state resynthesized from its harmonics. The simulation has no noise, so nothing
  here says anything about jitter or drift within a note.
- Temperature moves every transistor together; a temperature difference inside the converter pair is not
  in this table.
""")
(here / 'summary.md').write_text('\n'.join(L) + '\n')
print('\n'.join(L))
