#!/usr/bin/env python3
"""B1 report: summary.json + the 2026-10-16 B1-THT results -> <out>/summary.md."""
import json, pathlib
import numpy as np
import paths
here = paths.out('b1'); SRC = paths.SRC
S = json.loads((here / 'summary.json').read_text())
ref = {r['case']['id']: r['metrics'] for r in json.loads((SRC / 'b1-results-20261016.json').read_text())['results']}
L = []
def P(s=''): L.append(s)
cents = lambda a, b: 1200*np.log2(a / b)

P('# Step 1 - B1-THT in SPICE against the Mamut Analog oscillator'); P()
P('Generated by `driver/spice/vco/b1_report.py` from `summary.json` (`b1_analyze.py`) and `b1-results-20261016.json`.'); P()

P('## Pitch against CV'); P()
cv = np.array([r['cv'] for r in S]); f = np.array([r['f_hz'] for r in S])
lo = cv <= 1.5
a, b = np.polyfit(cv[lo], f[lo], 1)
su = np.array([r['shape']['slope_up'] for r in S]); sd = -np.array([r['shape']['slope_down'] for r in S])
vpp = np.array([r['shape']['vertex_hi'] - r['shape']['vertex_lo'] for r in S])
# reduced model: swing = dV + td * (su + sd); f = 1 / (swing * (1/su + 1/sd))
td2, dv = np.polyfit(su + sd, vpp, 1)
fm = 1 / ((dv + td2*(su + sd)) * (1/su + 1/sd))
pu = np.polyfit(cv, su, 1); pd = np.polyfit(cv, sd, 1)
su_l, sd_l = np.polyval(pu, cv), np.polyval(pd, cv)
fm2 = 1 / ((dv + td2*(su_l + sd_l)) * (1/su_l + 1/sd_l))
P('| CV (V) | f (Hz) | from a straight line (cents) | swing (V) | up (V/s) | down (V/s) | rise fraction | ramps + delay, measured slopes (cents) | slopes linear in CV (cents) |')
P('|---:|---:|---:|---:|---:|---:|---:|---:|---:|')
for i, r in enumerate(S):
    P(f"| {r['cv']:g} | {r['f_hz']:.3f} | {cents(f[i], a*cv[i] + b):+.2f} | {vpp[i]:.4f} | {su[i]:.1f} | {sd[i]:.1f} | "
      f"{r['shape']['rise_fraction']:.4f} | {cents(fm[i], f[i]):+.3f} | {cents(fm2[i], f[i]):+.2f} |")
P()
P(f'The straight line is fitted to CV <= 1.5 V: {a:.2f} Hz/V, zero at {-b/a:.3f} V. '
  f'The reduced model is a threshold distance of {dv:.4f} V and a switching delay of {1e6*td2:.2f} us per reversal '
  f'(fitted over the eight cases), with the two ramp slopes.'); P()

P('## Triangle output'); P()
P('| f (Hz) | H2 | H3 | H4 | H5 | H6 | H7 | even harmonics, total | SPICE - MA | SPICE - ideal | MA - ideal | two straight ramps, residual | residual peak |')
P('|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|')
for r in S:
    t = r['tri']; h = t['spice_dbc']
    P(f"| {r['f_hz']:.1f} | " + ' | '.join(f'{h[k]:.1f}' for k in range(1, 7)) +
      f" | {t['even_db']:.1f} | {t['null_vs_ma_db']:.1f} | {t['null_vs_ideal_db']:.1f} | {t['ma_vs_ideal_db']:.1f} | "
      f"{r['shape']['pwl_residual_db']:.1f} | {r['shape']['pwl_residual_peak_mv']:.1f} mV |")
P()
P('Harmonics in dB relative to the fundamental. The ideal triangle and MA have H3 -19.1, H5 -28.0, H7 -33.8 '
  'and no even harmonics (MA below -130 dB). The three difference columns are the power of the difference of '
  'two waveforms up to 20 kHz, after matching the fundamental in level and time, in dB relative to the first.'); P()

P('## Pulse output'); P()
P('| f (Hz) | duty | rise 10-90 % | fall | H2 | H3 | H4 | H5 | SPICE - MA | SPICE - ideal | MA - ideal |')
P('|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|')
for r in S:
    t = r['pulse']; h = t['spice_dbc']; m = t['ma_dbc']
    P(f"| {r['f_hz']:.1f} | {r['pulse_duty']:.4f} | {r['pulse_rise_us']:.2f} us | {r['pulse_fall_us']:.2f} us | " +
      ' | '.join(f'{h[k]:.1f} ({m[k]:.1f})' for k in range(1, 5)) +
      f" | {t['null_vs_ma_db']:.1f} | {t['null_vs_ideal_db']:.1f} | {t['ma_vs_ideal_db']:.1f} |")
P()
P('Harmonics as SPICE (MA at the same duty). The width trimmer is at its centre.'); P()

P('## Sensitivity of pitch (2026-10-16 run, CV 3 V, nominal %.3f Hz)' % ref['cv-3']['frequency_hz']); P()
P('| case | f (Hz) | cents |'); P('|---|---:|---:|')
n0 = ref['cv-3']['frequency_hz']
for k in ('supply-11.4', 'supply-12.6', 'temp-10-tc-0.0001', 'temp-10-tc--0.0001', 'temp-40-tc-0.0001', 'temp-40-tc--0.0001',
          'ref-offset--0.002', 'ref-offset-0.002', 'mirror-ratio-0.999', 'mirror-ratio-1.001', 'mismatch-0.8', 'mismatch-1.2',
          'beta-420', 'beta-800', 'early-30', 'early-200', 'resistors-low', 'resistors-high', 'timing-low', 'timing-high',
          'load-10k', 'load-1meg'):
    P(f"| {k} | {ref[k]['frequency_hz']:.3f} | {cents(ref[k]['frequency_hz'], n0):+.2f} |")
P()
tc = here / 'temp.json'
if tc.exists():
    T = json.loads(tc.read_text())
    P('Transistor temperature alone (reference ideal, this run, CV 2 V):'); P()
    P('| temperature | f (Hz) | cents | rise fraction | swing (V) |'); P('|---:|---:|---:|---:|---:|')
    base = next(x for x in T if x['temp'] == 25)
    for x in T:
        P(f"| {x['temp']} C | {x['f_hz']:.3f} | {cents(x['f_hz'], base['f_hz']):+.2f} | {x['rise_fraction']:.4f} | {x['swing']:.4f} |")
    P()
pm = here / 'phrase-measured.json'
if pm.exists():
    M = json.loads(pm.read_text())
    P('## Phrase (stepped CV, real transient)'); P()
    P(f"15 notes, {min(x['target_hz'] for x in M):.1f} to {max(x['target_hz'] for x in M):.1f} Hz. CV per note from a cubic through the "
      f"2026-10-16 points; SPICE lands within {min(x['cents'] for x in M):+.2f} to {max(x['cents'] for x in M):+.2f} cents of the "
      f"targets, duty {min(x['duty'] for x in M):.4f} to {max(x['duty'] for x in M):.4f}. MA plays the measured frequencies."); P()
P("""## Listening renders (`listen/`, 48 kHz, 24 bit, mono)

Each `-AB.wav` is SPICE, 0.4 s of silence, then MA, at the same RMS; `-spice.wav` and `-ma.wav` are the halves.

- `tone-tri-225Hz`, `tone-tri-801Hz`, `tone-tri-1943Hz`
- `tone-pulse-225Hz`, `tone-pulse-801Hz`, `tone-pulse-1943Hz`
- `phrase-tri`, `phrase-pulse`

## Method and limits

- DUT: the B1-THT bench of the 2026-10-16 run (`driver/spice/vco/b1-bench-cv-2.cir`, models in `models/`,
  hashes in `SHA256SUMS`), unchanged apart from the CV source, temperature and transient. ngspice-47, Gear,
  reltol 1e-5, 0.5 us maximum step, linearized to 1.92 MHz. The eight frequencies equal the 2026-10-16 ones.
- MA: `ma_ref.c`, the MA_SOURCE_EVIDENCE tick (sources only, no filter or envelope), VCO1 alone, 48 kHz
  (`make build/vco_ma_ref`).
- Harmonics: Blackman-Harris projection at k x f0, at least 12 cycles, up to 20 kHz. Waveform differences
  use the least-squares level and time shift over all harmonics.
- Tones are the SPICE steady state resynthesized from its harmonics; the period repeats to 1e-7, because
  the simulation has no noise. Nothing here says anything about jitter or drift.
- The transistor, reference and capacitor models are the lab's declared engineering models. No board has
  been measured. The pulse is measured at the centre of the width trimmer only.
""")
(here / 'summary.md').write_text('\n'.join(L) + '\n')
print('\n'.join(L))
